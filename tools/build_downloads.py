#!/usr/bin/env python3
"""Fill the downloads section of the landing page from the PDFs on disk.

    python3 tools/build_downloads.py <site-dir>

Looks for one-pager PDFs (and an optional bundle zip) in <site-dir>/downloads/
and rewrites the block between the DOWNLOADS:START and DOWNLOADS:END markers in
<site-dir>/index.html. Every known one-pager is listed; those with a PDF get a
download link, the others stay as plain entries. If no PDF is present at all,
the section says "Available on request". Always exits 0 when the page exists,
so a missing release never breaks the Pages build.
"""
import html
import os
import re
import sys

# (file-name key, title, one-line description), in display order.
# Keys match the PDF names of skainet-llc/witness-one-pagers, e.g.
# skAInet_WITNESS_Overview-v0.1.0.pdf or skAInet_WITNESS_Overview.pdf.
ONEPAGERS = [
    ("Overview", "Overview",
     "What WITNESS is and why it matters"),
    ("Platform_One-Pager", "Technology platform",
     "Architecture, devices, edge compute, rack variants"),
    ("Architecture", "Architecture",
     "Devices, edge compute, network, rack, learning loop"),
    ("Integration", "Integration",
     "Data in, base API, Docker facades to PLC, DCS, SCADA, ERP"),
    ("UseCase_RailwayPoints", "Use case: railway points",
     "Remaining life of point machines"),
    ("UseCase_SlideGates", "Use case: slide gates",
     "Early warning before a gate gets stuck"),
    ("UseCase_Valves", "Use case: motorised valves",
     "Early warning before a valve fails to open or close"),
    ("UseCase_AirFinCoolers", "Use case: air-fin coolers",
     "IR cameras find fouling and tell you when to clean"),
    ("Insurance_One-Pager", "For industrial insurers",
     "Physics-based data for dynamic risk assessment"),
]

START = "<!-- DOWNLOADS:START"
END = "<!-- DOWNLOADS:END -->"
MAIL = "mailto:hello@skainet.io?subject=WITNESS%20one-pagers"
NAME_RE = re.compile(r"^skAInet_WITNESS_(.+?)(?:-v?(\d+(?:\.\d+)*))?\.pdf$")


def version_key(v):
    return tuple(int(p) for p in v.split(".")) if v else ()


def find_pdfs(dldir):
    """Map one-pager key -> (file name, version) for the newest version."""
    found = {}
    if not os.path.isdir(dldir):
        return found
    for name in os.listdir(dldir):
        m = NAME_RE.match(name)
        if not m:
            continue
        key, ver = m.group(1), m.group(2) or ""
        if key not in found or version_key(ver) > version_key(found[key][1]):
            found[key] = (name, ver)
    return found


def find_bundle(dldir):
    if not os.path.isdir(dldir):
        return None
    zips = sorted(n for n in os.listdir(dldir) if n.lower().endswith(".zip"))
    return zips[-1] if zips else None


def size_label(path):
    kb = os.path.getsize(path) / 1024
    return "%d KB" % round(kb) if kb < 1024 else "%.1f MB" % (kb / 1024)


def render(dldir):
    found = find_pdfs(dldir)
    esc = html.escape
    lines = [START + " (generated by tools/build_downloads.py, do not edit by hand) -->",
             '    <ul class="dl-list">']
    for key, title, desc in ONEPAGERS:
        if key in found:
            name, ver = found[key]
            meta = "%s · PDF, %s%s" % (desc, size_label(os.path.join(dldir, name)),
                                      ", v" + ver if ver else "")
            lines.append(
                '      <li><a href="downloads/%s" download><span class="name">%s</span>'
                '<span class="meta">%s</span></a></li>'
                % (esc(name, quote=True), esc(title), esc(meta)))
        else:
            lines.append(
                '      <li><span class="na"><span class="name">%s</span>'
                '<span class="meta">%s</span></span></li>' % (esc(title), esc(desc)))
    lines.append("    </ul>")
    bundle = find_bundle(dldir)
    if bundle:
        lines.append(
            '    <p class="dl-bundle"><a class="btn btn-primary" href="downloads/%s" download>'
            "All one-pagers (zip, %s)</a></p>"
            % (esc(bundle, quote=True), size_label(os.path.join(dldir, bundle))))
    if not found:
        lines.append('    <p class="dl-note">Available on request: '
                     '<a href="%s">hello@skainet.io</a></p>' % MAIL)
    elif len(found) < len(ONEPAGERS):
        lines.append('    <p class="dl-note">Entries without a link are available on '
                     'request: <a href="%s">hello@skainet.io</a></p>' % MAIL)
    lines.append(END)
    return "\n".join(lines), len(found), bundle


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    site = sys.argv[1]
    page = os.path.join(site, "index.html")
    with open(page, encoding="utf-8") as f:
        text = f.read()
    a, b = text.find(START), text.find(END)
    if a < 0 or b < a:
        sys.exit("downloads markers not found in %s" % page)
    block, n, bundle = render(os.path.join(site, "downloads"))
    text = text[:a] + block + text[b + len(END):]
    with open(page, "w", encoding="utf-8") as f:
        f.write(text)
    print("downloads: %d of %d one-pagers linked%s"
          % (n, len(ONEPAGERS), ", bundle " + bundle if bundle else ""))


if __name__ == "__main__":
    main()
